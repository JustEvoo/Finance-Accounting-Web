export type LanguageCode = 'id' | 'en';

export function getTranslation(lang: string, key: keyof typeof translations['id'] | string, fallback?: string): string {
  const code = (lang === 'en' ? 'en' : 'id') as LanguageCode;
  const langDict = translations[code] as Record<string, string>;
  const enDict = translations['en'] as Record<string, string>;
  const idDict = translations['id'] as Record<string, string>;

  if (langDict && langDict[key as string]) {
    return langDict[key as string];
  }
  if (enDict && enDict[key as string]) {
    return enDict[key as string];
  }
  if (idDict && idDict[key as string]) {
    return idDict[key as string];
  }
  return fallback || (key as string);
}
